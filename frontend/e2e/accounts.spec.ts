import {expect, test} from "@playwright/test";
test.use({actionTimeout: 30_000});

// Only run with playwright.administration.config.ts: its fresh, isolated DB.
test("cuentas reales: cookie privada, unidades asignadas y cierre de sesión", async ({page, browser, baseURL}, testInfo) => {
  test.skip(baseURL !== "http://127.0.0.1:3006", "Requiere servidor y base aislados.");
  test.setTimeout(240_000);
  const password = process.env.YOKOHAMA_E2E_OWNER_PASSWORD || "e2e-only-password-2026";
  const changedPassword = "e2e-driver-new-password-2026";
  const issues: string[] = [];
  page.on("pageerror", error => issues.push(error.message));
  // Bootstrap is a server-owner operation, never a public registration form.
  const status = await page.request.get("/api/backend/auth/status");
  expect(status.status()).toBe(200);
  if (!(await status.json()).configured) {
    const setup = await page.request.post("/api/backend/auth/setup", {headers: {Origin: baseURL!}, data: {token: "isolated-test-setup-token-not-production-2026", name: "Administración de prueba", email: "admin.yoko@gmail.com", password}});
    expect(setup.status()).toBe(201);
    expect(await setup.json()).not.toHaveProperty("session_token");
  }
  await page.context().clearCookies();
  await page.goto("/acceso");
  await expect(page.getByLabel("Clave de activación del servidor")).toHaveCount(0);
  await page.getByLabel("Correo electrónico").fill("admin.yoko@gmail.com");
  await page.getByLabel("Contraseña", {exact: true}).fill(password);
  const loginResponse = page.waitForResponse(response => response.url().endsWith("/api/backend/auth/login"));
  await page.getByRole("button", {name: "Iniciar sesión", exact: true}).click();
  const login = await loginResponse;
  expect(login.status()).toBe(200);
  expect(await login.json()).not.toHaveProperty("session_token");
  await expect(page.getByRole("heading", {name: "Mi flotilla", exact: true})).toBeVisible();
  expect(await page.evaluate(() => document.cookie)).not.toContain("yokohama_session");
  const cookie = (await page.context().cookies()).find(item => item.name === "yokohama_session");
  expect(cookie?.httpOnly).toBe(true);
  expect(cookie?.sameSite).toBe("Strict");

  const unit = {vin: "1HGCM82633A004352", plate: "E2E-482-A", make: "Toyota", model: "Corolla", model_year: 2024, version: "Base", body_style: "sedán", engine: "2.0", transmission: "AT", drive: "FWD", current_km: 10000, in_service_date: "2024-01-01", nickname: "Mensajería", drivers: ["Nombre sin acceso automático"], is_synthetic: true};
  const created = await page.request.post("/api/backend/vehicles", {headers: {Origin: baseURL!}, data: unit});
  expect(created.status()).toBe(201);
  const vehicle = await created.json();
  const otherResponse = await page.request.post("/api/backend/vehicles", {headers: {Origin: baseURL!}, data: {...unit, vin: "1HGCM82633A004353", plate: "E2E-993-B", nickname: "Dirección"}});
  expect(otherResponse.status()).toBe(201);
  const other = await otherResponse.json();
  await page.goto("/cuenta");
  await expect(page.getByRole("heading", {name: "Usuarios", exact: true})).toBeVisible();
  await page.getByRole("link", {name: "Administrar usuarios", exact: true}).click();
  await expect(page).toHaveURL(/\/usuarios$/);
  await expect(page.getByRole("heading", {name: "Usuarios", exact: true})).toBeVisible();
  await page.getByRole("button", {name: "Agregar usuario", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Nuevo usuario", exact: true})).toBeVisible();
  await page.getByLabel("Nombre completo").fill("Capturista de prueba");
  await page.getByLabel("Correo de acceso").fill("captura@example.invalid");
  await page.getByLabel("Contraseña inicial").fill(password);
  await page.getByLabel("Confirmar contraseña", {exact: true}).fill(password);
  await page.getByRole("checkbox", {name: /E2E-482-A/}).check();
  await expect(page.getByLabel("Perfil", {exact: true})).toHaveCount(0);
  await page.getByRole("button", {name: "Crear usuario", exact: true}).click();
  await expect(page.getByText(/Usuario creado. Comparte/)).toBeVisible();
  const people = await (await page.request.get("/api/backend/users")).json();
  const operator = people.find((user: {email: string}) => user.email === "captura@example.invalid");
  expect(operator.vehicle_ids).toEqual([vehicle.id]);
  expect(JSON.stringify(people)).not.toContain(password);
  expect(JSON.stringify(people)).not.toContain("password_hash");
  await page.goto("/cuenta");
  const adminProfile = page.locator(".account-profile-fields");
  await expect(adminProfile.locator("div").filter({has: page.getByText("Nombre de usuario", {exact: true})}).locator("dd")).toHaveText("Administración de prueba");
  await expect(adminProfile.locator("div").filter({has: page.getByText("Correo electrónico", {exact: true})}).locator("dd")).toHaveText("admin.yoko@gmail.com");
  const adminAssigned = page.locator("section").filter({has: page.getByRole("heading", {name: "Unidades asignadas", exact: true})});
  await expect(adminAssigned.getByText("Sin unidades asignadas", {exact: true})).toBeVisible();
  await expect(adminAssigned.locator("li")).toHaveCount(0);

  const userContext = await browser.newContext({baseURL, viewport: {width: 390, height: 844}});
  const userPage = await userContext.newPage();
  userPage.on("pageerror", error => issues.push(error.message));
  await userPage.goto("/acceso");
  await userPage.getByLabel("Correo electrónico").fill("captura@example.invalid");
  await userPage.getByLabel("Contraseña", {exact: true}).fill(password);
  await userPage.getByRole("button", {name: "Iniciar sesión", exact: true}).click();
  await expect(userPage.getByRole("link", {name: "E2E-482-A", exact: true}).first()).toBeVisible();
  await expect(userPage.getByText("E2E-993-B", {exact: true})).toHaveCount(0);
  await expect(userPage.getByRole("button", {name: "Agregar unidad", exact: true})).toHaveCount(0);
  await userPage.getByRole("button", {name: /YOKOHAMA.*Operación/}).click();
  await expect(userPage.getByRole("navigation").getByRole("link", {name: "Usuarios", exact: true})).toHaveCount(0);
  await expect(userPage.getByRole("navigation").getByRole("link", {name: "Resumen", exact: true})).toHaveCount(0);
  expect(await userPage.getByRole("navigation").getByRole("link").allTextContents()).toEqual(["Mis unidades", "Incidencias", "Kilometraje", "Fallas", "Mi cuenta"]);
  await userPage.keyboard.press("Escape");
  await expect(userPage.getByRole("navigation")).toHaveCount(0);
  expect((await userContext.request.get(`/api/backend/vehicles/${other.id}`)).status()).toBe(404);
  expect((await userContext.request.get("/api/backend/users")).status()).toBe(403);
  expect((await userContext.request.get("/api/backend/metrics")).status()).toBe(403);
  expect((await userContext.request.get("/api/backend/fleet-statistics")).status()).toBe(403);
  expect((await userContext.request.get(`/api/backend/vehicles/${vehicle.id}/plan`)).status()).toBe(403);
  expect((await userContext.request.patch(`/api/backend/vehicles/${vehicle.id}/administration`, {headers: {Origin: baseURL!}, data: {nickname: "Intento denegado"}})).status()).toBe(403);
  const photo = await userPage.evaluate(() => {const canvas = document.createElement("canvas"); canvas.width = 16; canvas.height = 16; canvas.getContext("2d")!.fillRect(0, 0, 16, 16); return canvas.toDataURL("image/png");});
  const image = {name: "tablero.png", mimeType: "image/png", buffer: Buffer.from(photo.split(",")[1], "base64")};
  const privateReportResponse = await page.request.post(`/api/backend/vehicles/${vehicle.id}/incidents`, {headers: {Origin: baseURL!}, data: {occurred_on: "2026-09-25", category: "otro", description: "Reporte privado del administrador en unidad compartida", photos: [{filename: "privada.png", data_url: photo}]}});
  expect(privateReportResponse.status()).toBe(201);
  const privateReport = await privateReportResponse.json();
  expect((await userContext.request.get(`/api/backend/evidence/${privateReport.photos[0].id}`)).status()).toBe(404);

  await userPage.goto("/kilometraje");
  const observed = userPage.getByLabel("Fecha y hora de lectura (CDMX)");
  await expect(observed).toBeVisible();
  const previousDay = new Date(`${(await observed.inputValue()).slice(0, 10)}T12:00:00Z`);
  previousDay.setUTCDate(previousDay.getUTCDate() - 1);
  const day = previousDay.toISOString().slice(0, 10);
  await observed.fill(`${day}T10:15`);
  const kilometraje = userPage.getByLabel("Kilometraje (km)", {exact: true});
  await expect(kilometraje).toHaveAttribute("type", "text");
  await expect(kilometraje).toHaveAttribute("inputmode", "decimal");
  await expect(userPage.getByLabel("Fuente de lectura")).toHaveCount(0);
  await kilometraje.fill("9950");
  await userPage.getByLabel("Fotos del kilometraje (máximo 3)").setInputFiles(image);
  await expect(userPage.getByAltText("Vista previa: tablero.jpg")).toBeVisible();
  const readingResponse = userPage.waitForResponse(response => response.url().endsWith(`/api/backend/vehicles/${vehicle.id}/odometer-captures`) && response.request().method() === "POST");
  await userPage.getByRole("button", {name: "Guardar kilometraje", exact: true}).click();
  const readingResult = await readingResponse;
  expect(readingResult.status()).toBe(201);
  expect(readingResult.request().postDataJSON().source).toBe("manual");
  const reading = await readingResult.json();
  expect(reading.captured_by).toBe(operator.id);
  expect(reading.photos).toHaveLength(1);
  await expect(userPage.getByText("Kilometraje y fotos guardados.", {exact: true})).toBeVisible();
  expect((await userContext.request.get(`/api/backend/evidence/${reading.photos[0].id}`)).status()).toBe(200);
  const incidentResponse = await userContext.request.post(`/api/backend/vehicles/${vehicle.id}/incidents`, {headers: {Origin: baseURL!}, data: {occurred_on: "2026-09-25", category: "otro", description: "Rayón observado en puerta durante revisión de prueba.", photos: [{filename: "revision.png", data_url: photo}]}});
  expect(incidentResponse.status()).toBe(201);
  const incident = await incidentResponse.json();
  expect(incident.captured_by).toBe(operator.id);
  await userPage.goto("/incidencias");
  await expect(userPage.getByText("Rayón observado en puerta durante revisión de prueba.", {exact: true})).toBeVisible();
  await expect(userPage.getByText("Reporte privado del administrador en unidad compartida", {exact: true})).toHaveCount(0);
  expect(await userPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await userPage.goto(`/vehiculos/${vehicle.id}`);
  await expect(userPage.getByRole("heading", {name: "Documentación y vencimientos", exact: true})).toBeVisible();
  await expect(userPage.getByRole("button", {name: "Guardar documentación", exact: true})).toHaveCount(0);
  await expect(userPage.getByLabel("Inicio del periodo de verificación", {exact: true})).toHaveCount(0);
  await expect(userPage.getByRole("heading", {name: "Plan de mantenimiento", exact: true})).toHaveCount(0);
  await expect(userPage.getByText("Rayón observado en puerta durante revisión de prueba.", {exact: true})).toHaveCount(0);
  await userPage.goto("/fallas");
  await userPage.getByLabel("Fecha en que detectaste la falla").fill(day);
  await userPage.getByLabel("¿Qué problema observaste?").fill("Ruido en suspensión observado durante recorrido de prueba.");
  await userPage.getByLabel("Prioridad").selectOption("menor");
  await userPage.getByLabel("Fotos de la falla (máximo 3)").setInputFiles({...image, name: "falla.png"});
  await expect(userPage.getByAltText("Vista previa: falla.jpg")).toBeVisible();
  const faultResponse = userPage.waitForResponse(response => response.url().endsWith(`/api/backend/vehicles/${vehicle.id}/faults`) && response.request().method() === "POST");
  await userPage.getByRole("button", {name: "Guardar reporte de falla", exact: true}).click();
  const faultResult = await faultResponse;
  expect(faultResult.status()).toBe(201);
  const fault = await faultResult.json();
  expect(fault.captured_by).toBe(operator.id);
  expect(fault.photos).toHaveLength(1);
  await expect(userPage.getByText("Ruido en suspensión observado durante recorrido de prueba.", {exact: true})).toBeVisible();
  await expect(userPage.getByRole("button", {name: "Registrar solución", exact: true})).toHaveCount(0);
  expect((await userContext.request.patch(`/api/backend/faults/${fault.id}/resolve`, {headers: {Origin: baseURL!}, data: {resolution_notes: "Intento del conductor sin permisos", photos: [{filename: "intento.png", data_url: photo}]}})).status()).toBe(403);
  const unchangedFault = (await (await userContext.request.get(`/api/backend/vehicles/${vehicle.id}`)).json()).faults.find((item: {id: number}) => item.id === fault.id);
  expect(unchangedFault.status).toBe("open");
  expect(unchangedFault.resolution_notes).toBe(fault.resolution_notes);
  expect(unchangedFault.photos).toHaveLength(1);

  // Admin resolution is a real UI action on a private fixture report, not a new report.
  const adminFaultDescription = "Falla privada del administrador para verificar su solución con evidencia.";
  const resolutionNotes = "Se reemplazó la pieza dañada y se comprobó su funcionamiento en taller.";
  const adminFaultResponse = await page.request.post(`/api/backend/vehicles/${vehicle.id}/faults`, {headers: {Origin: baseURL!}, data: {reported_on: day, description: adminFaultDescription, severity: "menor", photos: [{filename: "antes.png", data_url: photo}]}});
  expect(adminFaultResponse.status()).toBe(201);
  const adminFault = await adminFaultResponse.json();
  await page.goto(`/fallas?unidad=${vehicle.id}`);
  const adminReport = page.locator("article").filter({has: page.getByText(adminFaultDescription, {exact: true})});
  await expect(adminReport).toHaveCount(1);
  await expect(adminReport.getByLabel("Describe la solución aplicada")).toHaveCount(0);
  await adminReport.getByRole("button", {name: "Registrar solución", exact: true}).click();
  await expect(adminReport.getByRole("region", {name: `Registrar solución del reporte #${adminFault.id}`, exact: true})).toBeVisible();
  await adminReport.getByLabel("Describe la solución aplicada").fill(resolutionNotes);
  await adminReport.getByLabel("Fotos de la solución (máximo 3)").setInputFiles({...image, name: "solucion.png"});
  await expect(adminReport.getByAltText("Vista previa: solucion.jpg")).toBeVisible();
  await page.screenshot({path: testInfo.outputPath("fallas-solucion-administrador.png"), fullPage: true});
  const resolutionResponse = page.waitForResponse(response => response.url().endsWith(`/api/backend/faults/${adminFault.id}/resolve`) && response.request().method() === "PATCH");
  await adminReport.getByRole("button", {name: "Guardar solución y cerrar reporte", exact: true}).click();
  const resolutionResult = await resolutionResponse;
  expect(resolutionResult.status()).toBe(200);
  const resolvedFault = await resolutionResult.json();
  expect(resolvedFault.id).toBe(adminFault.id);
  expect(resolvedFault.status).toBe("resolved");
  expect(resolvedFault.resolution_notes).toBe(resolutionNotes);
  expect(resolvedFault.photos).toHaveLength(2);
  const solutionPhoto = resolvedFault.photos.find((item: {filename: string}) => item.filename === "solucion.jpg");
  expect(solutionPhoto).toBeDefined();
  expect(solutionPhoto.fault_id).toBe(adminFault.id);
  await expect(page.getByLabel("Filtrar fallas")).toHaveValue("all");
  await expect(adminReport.getByText(`Solución: ${resolutionNotes}`, {exact: true})).toBeVisible();
  await expect(adminReport.getByRole("button", {name: "Registrar solución", exact: true})).toHaveCount(0);
  await page.reload();
  await page.getByLabel("Filtrar fallas").selectOption("all");
  await expect(adminReport).toHaveCount(1);
  await expect(adminReport.getByText(`Solución: ${resolutionNotes}`, {exact: true})).toBeVisible();
  await expect(adminReport.getByRole("button", {name: /^Ver foto \d+$/})).toHaveCount(2);
  const reportGallery = (await (await page.request.get(`/api/backend/vehicles/${vehicle.id}/evidence`)).json()).filter((item: {fault_id: number}) => item.fault_id === adminFault.id);
  const solutionPhotoIndex = reportGallery.findIndex((item: {id: string}) => item.id === solutionPhoto.id);
  expect(solutionPhotoIndex).toBeGreaterThanOrEqual(0);
  await adminReport.getByRole("button", {name: `Ver foto ${solutionPhotoIndex + 1}`, exact: true}).click();
  await expect(page.getByRole("dialog", {name: "Fotografía adjunta", exact: true}).getByAltText("Evidencia: solucion.jpg")).toBeVisible();
  await page.getByRole("button", {name: "Cerrar foto", exact: true}).click();
  const adminHistory = (await (await page.request.get(`/api/backend/vehicles/${vehicle.id}`)).json()).faults;
  expect(adminHistory.filter((item: {id: number}) => item.id === adminFault.id)).toHaveLength(1);
  expect(adminHistory.filter((item: {description: string}) => item.description === adminFaultDescription)).toHaveLength(1);
  expect((await userContext.request.get(`/api/backend/evidence/${solutionPhoto.id}`)).status()).toBe(404);
  await userPage.reload();
  await userPage.getByLabel("Filtrar fallas").selectOption("all");
  await expect(userPage.getByText(adminFaultDescription, {exact: true})).toHaveCount(0);
  await expect(userPage.getByText(resolutionNotes, {exact: true})).toHaveCount(0);
  await expect(userPage.getByText("Ruido en suspensión observado durante recorrido de prueba.", {exact: true})).toBeVisible();

  await userPage.goto("/cuenta");
  await expect(userPage.getByRole("heading", {name: "Usuarios", exact: true})).toHaveCount(0);
  await expect(userPage.getByRole("link", {name: "Administrar usuarios", exact: true})).toHaveCount(0);
  const driverProfile = userPage.locator(".account-profile-fields");
  await expect(driverProfile.locator("div").filter({has: userPage.getByText("Nombre de usuario", {exact: true})}).locator("dd")).toHaveText("Capturista de prueba");
  await expect(driverProfile.locator("div").filter({has: userPage.getByText("Correo electrónico", {exact: true})}).locator("dd")).toHaveText("captura@example.invalid");
  const driverAssigned = userPage.locator("section").filter({has: userPage.getByRole("heading", {name: "Unidades asignadas", exact: true})});
  await expect(driverAssigned.locator("li")).toHaveCount(1);
  await expect(driverAssigned.locator(`a[href='/vehiculos/${vehicle.id}']`)).toContainText("E2E-482-A");
  await expect(driverAssigned.locator(`a[href='/vehiculos/${other.id}']`)).toHaveCount(0);
  await expect(driverAssigned.getByText("E2E-993-B", {exact: true})).toHaveCount(0);
  const passwordPanel = userPage.locator("section").filter({has: userPage.getByRole("heading", {name: "Cambiar contraseña", exact: true})});
  await passwordPanel.getByRole("button", {name: "Mostrar más"}).click();
  await expect(userPage.getByLabel("Escribe tu contraseña actual")).toHaveValue("");
  await expect(userPage.getByLabel("Escribe tu contraseña actual")).toHaveAttribute("type", "password");
  await userPage.getByLabel("Escribe tu contraseña actual").fill(password);
  await userPage.getByLabel("Nueva contraseña", {exact: true}).fill(changedPassword);
  await userPage.getByLabel("Confirmar nueva contraseña").fill(changedPassword);
  const changeResponse = userPage.waitForResponse(response => response.url().endsWith("/api/backend/auth/password"));
  await userPage.getByRole("button", {name: "Guardar nueva contraseña", exact: true}).click();
  expect((await changeResponse).status()).toBe(200);
  await expect(userPage.getByRole("heading", {name: "Bienvenido a Yokohama", exact: true})).toBeVisible();
  expect((await userContext.request.get("/api/backend/vehicles")).status()).toBe(401);
  const oldLogin = await userContext.request.post("/api/backend/auth/login", {headers: {Origin: baseURL!}, data: {email: "captura@example.invalid", password}});
  expect(oldLogin.status()).toBe(401);
  await userPage.getByLabel("Correo electrónico").fill("captura@example.invalid");
  await userPage.getByLabel("Contraseña", {exact: true}).fill(changedPassword);
  await userPage.getByRole("button", {name: "Iniciar sesión", exact: true}).click();
  await expect(userPage.getByRole("heading", {name: "Mis unidades", exact: true})).toBeVisible();
  await userPage.getByRole("button", {name: "Salir", exact: true}).click();
  await expect(userPage.getByRole("heading", {name: "Entra a tu cuenta"})).toBeVisible();
  expect((await userContext.request.get("/api/backend/vehicles")).status()).toBe(401);
  await userContext.close();
  expect(issues).toEqual([]);
});
